/** Share of answered ratings that are positive (4 or 5 out of 5). */
export function positiveShare(values: (number | null)[]) {
  const n = values.filter((v): v is number => v !== null);
  return n.length ? n.filter((v) => v >= 4).length / n.length : 0;
}
